import { writeFileSync } from "node:fs";
import { ROUTINES, simulate, TOTAL_UPGRADES } from "../../lib/earned/sim/balance";
import { expectedChestCredits } from "../../lib/earned/domain/loot";
import { totalEstateCost } from "../../lib/earned/domain/estate";

/** Runs the balance simulator for each routine and writes docs/earned/balance-report.md. */
async function main() {
  const days = 120;
  const rows: string[] = [];
  const detail: string[] = [];
  for (const routine of ROUTINES) {
    const r = await simulate(routine, days);
    const last = r.days[r.days.length - 1];
    const minVit = Math.min(...r.days.map((d) => d.vitality));
    rows.push(
      `| ${routine.name} | ${r.dayReached[5] ?? "–"} | ${r.dayReached[10] ?? ">" + days} | ${(last.chestsEarned / days).toFixed(2)} | ${(last.ticketsEarned / days).toFixed(2)} | ${r.firstUpgradeDay ?? "–"} | ${r.upgradesBy[30]}/${r.upgradesBy[60]}/${r.upgradesBy[90]}/${r.upgradesBy[120]} | ${minVit} |`,
    );
    const total = Object.values(r.creditSources).reduce((s, x) => s + x, 0);
    detail.push(
      `- **${routine.name}**: ${total} Estate Credits earned in ${days} days (chests ${r.creditSources.chest ?? 0}, duplicates ${r.creditSources.duplicate ?? 0}, momentum ${r.creditSources.momentum ?? 0}, ventures ${r.creditSources.battle ?? 0}); ventures ${r.battles.victories}/${r.battles.played} victories; level ${last.level} (${last.xp} XP) on day ${days}.`,
    );
    console.log(`done: ${routine.name}`);
  }
  const md = `# Earned balance report

Generated by \`npm run earned:balance\` (lib/earned/sim/balance.ts). Each routine is played day by day through the real rules in memory: minimums completed per the routine, every chest opened, every ticket spent on a rewarded venture with an informed strategy (scout, then counter), and the cheapest available estate upgrade bought whenever affordable. ${days} simulated days.

**Reference estimate:** three daily minimums at 10 XP = 30 XP/day reaches Level 10 (2,700 XP) on day 90. That's an estimate for that routine, not a promise: optional effort and extra quests shorten it; misses lengthen it. Thresholds never change with performance.

| Routine | Day L5 | Day L10 | Chests/day | Tickets/day | First upgrade (day) | Upgrades by day 30/60/90/120 (of ${TOTAL_UPGRADES}) | Lowest vitality |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

${detail.join("\n")}

Reference numbers: expected credits per chest before duplicates ≈ ${expectedChestCredits().toFixed(1)}; full estate costs ${totalEstateCost()} credits; momentum adds up to 5 per success; a rewarded venture pays 10 (+15 victory / +5 partial).

**Reading it:** attendance alone drives every system: XP, chests, tickets, and therefore credits and the estate. Ventures roughly double credit income but are capped by tickets (two per day), so there is no grind unrelated to real habits. Early upgrades land in the first week; the estate fills over months, gated by level (which only real-world quests raise).
`;
  writeFileSync("docs/earned/balance-report.md", md);
  console.log("Wrote docs/earned/balance-report.md");
}

void main();
