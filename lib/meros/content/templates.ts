const daily = (start: string, end: string): Schedule => ({ kind: "daily", window: { start, end } });
const weekdays = (days: number[], start: string, end: string): Schedule => ({ kind: "weekdays", days, window: { start, end } });
const weekly = (n: number, start: string, end: string): Schedule => ({ kind: "weekly", timesPerWeek: n, window: { start, end } });
const photo = (...criteria: string[]) => ({ mode: "photo" as const, criteria });
const gps = (locationHint: string, ...criteria: string[]) => ({ mode: "gps" as const, criteria, locationHint });

