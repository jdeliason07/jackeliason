import type { Schedule } from "../domain/schedule";

/**
 * Fifty editable quest templates. Each minimum action is small and observable; photos show
 * preparation or a visible state (an open book, shoes by the door), never people, private messages,
 * medical documents, or financial accounts. For private activities (prayer, journaling) the evidence
 * is preparation, and the criteria say so plainly. GPS templates never include coordinates: the
 * owner sets the location during setup.
 *
 * Distribution: fitness 9, learning 8, business/work 8, reflection/faith 9, relationships/service 8,
 * household 8. The two extra slots went to fitness and faith: physical training and spiritual study
 * are the owner's stated daily anchors.
 */

export type QuestCategory = "fitness" | "learning" | "business" | "faith" | "relationships" | "household";
export type VerificationMode = "photo" | "gps";

export interface QuestTemplate {
  id: string;
  title: string;
  category: QuestCategory;
  purpose: string;
  minimumAction: string;
  extension: string;
  cue: string;
  schedule: Schedule;
  verification: { mode: VerificationMode; criteria: string[]; locationHint?: string };
  maxXp: number;
  reviewIntervalDays: number;
}

